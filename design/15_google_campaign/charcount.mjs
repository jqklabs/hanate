#!/usr/bin/env node
/* 구글 Ads 글자수 검증 — 한/중/일 문자는 2로 계산된다(2바이트 언어).
 * copy.md의 문구를 고치면 여기도 고치고 `node charcount.mjs`로 다시 확인한다.
 * 한도를 넘으면 등록 단계에서 잘려 문장이 깨진다. */

const width = (s) =>
  [...s].reduce((n, c) => n + (/[ㄱ-ㆎ가-힣一-鿿぀-ヿ]/.test(c) ? 2 : 1), 0);

const SETS = [
  ['짧은 광고제목', 30, [
    '화투로 12월까지 깰 수 있어?',
    '혼자 하는 고스톱 로그라이크',
    '오광 ×12, 점수가 터진다',
    'AI 봇도 못 깬 화투 게임',
    '설치 없이 브라우저에서 무료',
    '당신은 몇 월에서 죽나요?',            // 예비
  ]],
  ['긴 광고제목', 90, [
    '화투 48장으로 하는 로그라이크 덱빌딩',
    '족보 13종, 특수패 22종, 1월부터 12월까지',
    '목표 160점에서 5,500점까지 — 몇 월에서 죽나요?',
    '고를 외칠 것인가, 스톱하고 도망갈 것인가',
    '고도리·삼광·오광, 아는 족보로 점수를 터뜨린다',
  ]],
  ['설명', 90, [
    '손패 8장으로 족보를 맞추고 목표를 넘기세요. 설치 없는 무료 웹게임.',
    '특수패 22종으로 빌드를 키우면 점수가 터집니다. 지금 바로 플레이.',
    '고를 외치면 목표가 커집니다. 실패하면 고박, 런은 그대로 끝.',
    '1월부터 12월까지 12판. 3·6·9·12월엔 박이 판을 비틉니다.',
    '그리디 AI 봇 승률 0%. 12월까지 갈 수 있는지 확인해보세요.',
    '설치도 로그인도 없습니다. 브라우저에서 바로 시작하세요.',   // 예비
  ]],
  ['짧은 설명', 60, ['족보를 맞춰 목표를 넘기는 화투 덱빌딩.']],
  ['업체명', 25, ['화투로']],
];

/* 정책상 쓰면 안 되는 단어 — 소셜 카지노 분류 유발 / 타사 상표 (README §4) */
const BANNED = ['내기', '베팅', '배팅', '도박', '판돈', '잭팟', '당첨', '발라트로'];

let bad = 0;
for (const [name, limit, items] of SETS) {
  console.log(`\n== ${name} (한도 ${limit} · 한글 ${limit / 2}자) ==`);
  for (const s of items) {
    const w = width(s);
    const hit = BANNED.filter((b) => s.includes(b));
    const ok = w <= limit && hit.length === 0;
    if (!ok) bad++;
    console.log(`${String(w).padStart(3)}/${limit} ${ok ? 'OK  ' : 'FAIL'} ${s}` +
                (hit.length ? `   ← 금지어: ${hit.join(', ')}` : ''));
  }
}
console.log(bad ? `\n${bad}건 위반` : '\n전부 통과');
process.exit(bad ? 1 : 0);
